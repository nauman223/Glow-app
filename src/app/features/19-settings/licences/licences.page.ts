import { ChangeDetectionStrategy, Component, inject } from '@angular/core';
import { RouterLink } from '@angular/router';
import { APP_ROUTES } from '@core/config/app.constants';
import { IonContent } from '@ionic/angular/ion-content';
import { IonHeader } from '@ionic/angular/ion-header';
import { IonToolbar } from '@ionic/angular/ion-toolbar';
import { CardComponent } from '@shared/ui/card/card.component';
import { IconComponent } from '@shared/ui/icon/icon.component';
import { SkeletonComponent } from '@shared/ui/skeleton/skeleton.component';
import { StateMessageComponent } from '@shared/ui/state-message/state-message.component';

import { LicenceItemComponent } from './components/licence-item/licence-item.component';
import { type LicenceComponent } from './licences.models';
import { LicencesStore } from './licences.store';
import { LICENCES_STRINGS } from './licences.strings';

/**
 * Settings → Open-source licences: every bundled third-party component (fonts, AI models,
 * libraries) with its licence. The list and texts are static files generated by
 * `npm run licences`; texts load only when expanded.
 */
@Component({
  selector: 'app-licences-page',
  changeDetection: ChangeDetectionStrategy.OnPush,
  providers: [LicencesStore],
  imports: [
    IonHeader,
    IonToolbar,
    IonContent,
    RouterLink,
    CardComponent,
    IconComponent,
    SkeletonComponent,
    StateMessageComponent,
    LicenceItemComponent,
  ],
  templateUrl: './licences.page.html',
  styleUrl: './licences.page.scss',
})
export class LicencesPage {
  private readonly store = inject(LicencesStore);

  protected readonly strings = LICENCES_STRINGS;
  protected readonly settingsRoute = APP_ROUTES.settings;
  protected readonly status = this.store.status;
  protected readonly sections = this.store.sections;

  constructor() {
    void this.store.load();
  }

  protected retry(): void {
    void this.store.load();
  }

  protected toggle(component: LicenceComponent): void {
    this.store.toggle(component);
  }

  protected retryText(component: LicenceComponent): void {
    this.store.retryText(component);
  }
}
